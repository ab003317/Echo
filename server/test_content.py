    assert evaluate(dict(title='Song 歌ってみた',duration=204,categories=['Entertainment'],channel_is_verified=True,
        description='Vocal: A\nInst: B\nMix: C'))[0]=='approved'
    assert evaluate(dict(title='Song - TOUR 2024 公演',duration=242,categories=['Music'],channel_is_verified=True))[0]=='approved'


