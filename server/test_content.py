@pytest.mark.parametrize('title', ['Full Album', '歌手完整合集', 'Songs Compilation', 'Full Concert', 'Piano Medley'])
def test_complete_music_collections_can_enter_automatic_pool(title):
    info = dict(title=title, duration=5400, categories=['Music'], channel_is_verified=True)
    assert evaluate(info)[0] == 'approved'
    assert metadata(info)['contentKind'] == 'collection'
    assert evaluate({**info, 'channel_is_verified': False})[0] == 'review'
    assert evaluate({**info, 'title': title+' Preview'})[0] == 'rejected'


def test_track_chapters_and_description_identify_collections_not_song_sections():
    base = dict(title='Concert recording', duration=5400, categories=['Music'], channel_is_verified=True)
    chapters = [{ 'title': 'Artist A - Song One', 'start_time': 0 }, { 'title': 'Artist B - Song Two', 'start_time': 240 }]
    assert content_kind({**base, 'chapters': chapters}) == 'collection'
    assert evaluate({**base, 'chapters': chapters})[0] == 'approved'
    listed = {**base, 'description': 'Tracklist\n00:00 Artist A - Song One\n04:00 Artist B - Song Two'}
    assert evaluate(listed)[0] == 'approved'
    assert content_kind(listed) == 'collection'
    single = {**base, 'title': 'Song Official Audio', 'description': '00:00 Intro\n00:10 Verse 1\n00:40 Chorus\n01:10 Bridge'}
    assert content_kind(single) == 'single'
    assert evaluate(single)[0] == 'approved'
    teaching = {**base, 'title': 'Full Album guitar tutorial', 'chapters': chapters}
    assert evaluate(teaching)[0] == 'rejected'
    assert content_kind(released('Playlist', 240)) == 'single'


def test_stale_policy_rechecks_and_requeues_long_music_but_keeps_user_reports(api):
    c, a = api
    a.radio.queue_candidates([{'id':'abcdefghijk','title':'Full Album','duration':5400},
                              {'id':'bcdefghijkl','title':'Full Concert','duration':7200}], 2)
    info = dict(title='Full Album', duration=5400, categories=['Music'], channel_is_verified=True)
    a.quality.record('abcdefghijk', 'rejected', '整张专辑或拼接歌单', info)
    a.quality.record('bcdefghijkl', 'rejected', '用户标记为非完整歌曲', info)
    with a.db() as con:
        con.execute('UPDATE content_checks SET policy=2')
        con.execute("UPDATE jobs SET status='rejected'")
    a.quality.initialize()
    with a.db() as con:
        assert con.execute("SELECT status FROM content_checks WHERE video='abcdefghijk'").fetchone()[0] == 'approved'
        assert con.execute("SELECT status FROM jobs WHERE video='abcdefghijk'").fetchone()[0] == 'queued'
        assert con.execute("SELECT status FROM jobs WHERE video='bcdefghijkl'").fetchone()[0] == 'rejected'
        assert {r[0] for r in con.execute('SELECT policy FROM content_checks')} == {POLICY}


def test_search_queue_and_download_do_not_truncate_complete_collections(api, monkeypatch):
    c, a = api
    def search(*args, **kwargs):
        return subprocess.CompletedProcess(args, 0, json.dumps({'entries': [
            {'id':'abcdefghijk','title':'Full Album','duration':5400},
            {'id':'bcdefghijkl','title':'Short complete work','duration':17},
            {'id':'cdefghijklm','title':'Live now','duration':7200,'is_live':True}]}), '')
    monkeypatch.setattr(a.subprocess, 'run', search)
    rows, _ = a.search_youtube('duration-regression')
    assert {r['id'] for r in rows} == {'abcdefghijk', 'bcdefghijkl'}
    assert a.radio.queue_candidates(rows, 2) == 2
    monkeypatch.setattr(a, 'youtube_info', lambda video: dict(title='Full Album',duration=5400,categories=['Music'],channel_is_verified=True))
    commands = []
    def download(cmd, **kwargs):
        commands.append(cmd)
        return subprocess.CompletedProcess(cmd, 1, '', 'Fixture stops before transferring audio')
    monkeypatch.setattr(a.subprocess, 'run', download)
    with a.db() as con:
        job = dict(con.execute("SELECT * FROM jobs WHERE video='abcdefghijk'").fetchone())
    a.import_job(job)
    assert commands
    assert commands[0][commands[0].index('--match-filter')+1] == '!is_live'
    assert commands[0][commands[0].index('--max-filesize')+1] == '300M'
